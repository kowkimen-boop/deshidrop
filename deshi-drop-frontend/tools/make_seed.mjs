/* Generates supabase/seed.sql from the CURRENT website (products, deals, every translated text, default settings).
   Run it again whenever you change products/text in the code and want a fresh seed file:

     python3 -m http.server 8123 &                      # serve the site folder
     PPT_MODULES=/path/with/node_modules node tools/make_seed.mjs

   Needs puppeteer-core + a Chromium (CHROME env var, default below). */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const req = createRequire((process.env.PPT_MODULES ? process.env.PPT_MODULES.replace(/\/?$/, '/') : here + '/') + 'x.js');
const puppeteer = req('puppeteer-core');
const URL_ = process.env.SITE_URL || 'http://localhost:8123/';
const CHROME = process.env.CHROME || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';

const used = new Set();
function lit(s) {                                     // safe SQL string literal via dollar quoting
  if (s === null || s === undefined) return 'null';
  s = String(s);
  let i = 0, tag;
  do { tag = '$q' + i++ + '$'; } while (s.includes(tag));
  return tag + s + tag;
}
const num = (n) => (n === null || n === undefined || n === '' ? 'null' : String(n));
const bool = (b) => (b ? 'true' : 'false');
function unitOf(name) {
  if (/\(per lb\)/i.test(name)) return 'lb';
  if (/per piece/i.test(name)) return 'piece';
  if (/\b\d+(\.\d+)?\s*(lb|kg|l|gal|ct|oz)\b|\d+-pack/i.test(name)) return 'pack';
  return 'each';
}

const browser = await puppeteer.launch({ executablePath: CHROME, args: ['--no-sandbox'] });
const page = await browser.newPage();
await page.setViewport({ width: 420, height: 900 });
await page.goto(URL_, { waitUntil: 'load' });
await new Promise((r) => setTimeout(r, 1200));

const data = await page.evaluate(() => {
  const D = window.__DD;
  const products = D.products.map((p, i) => ({
    name: p.name, name_bn: D.pName(p, 'bn'), name_ar: D.pName(p, 'ar'),
    category: p.cat, category_bn: D.pCat(p, 'bn'), category_ar: D.pCat(p, 'ar'),
    sub: p.sub || null, price: parseFloat(String(p.price).replace(/[^0-9.]/g, '')),
    tag: p.tag || null, photo_key: p.photo || null, icon: p.icon || null, sort: i,
  }));
  return { products, deals: (window.__DEALS || []).map((d, i) => ({ name: d.name, pct: d.pct, sort: i, active: d.active !== false, from: d.from || null, until: d.until || null })),
    cfg: window.__DEALS_CONFIG || {} };
});

const content = {};                                   // key -> {en, bn, ar}
for (const lang of ['en', 'bn', 'ar']) {
  await page.evaluate((l) => document.querySelector('.lang-opt[data-lang="' + l + '"]').click(), lang);
  await new Promise((r) => setTimeout(r, 500));
  const got = await page.evaluate(() => {
    const out = {};
    document.querySelectorAll('[data-i18n]').forEach((el) => { const k = el.getAttribute('data-i18n'); if (!(k in out)) out[k] = el.textContent; });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => { const k = 'ph:' + el.getAttribute('data-i18n-ph'); if (!(k in out)) out[k] = el.getAttribute('placeholder'); });
    return out;
  });
  for (const [k, v] of Object.entries(got)) (content[k] = content[k] || {})[lang] = v;
}
await browser.close();

const L = [];
L.push('-- Deshi Drop — seed data, generated by tools/make_seed.mjs from the current website.');
L.push('-- Run AFTER schema.sql. Safe to run again: rows that already exist are left alone, so your dashboard edits are never overwritten.');
L.push('');
L.push('-- ---- products');
for (const p of data.products) {
  L.push(`insert into products (name, name_bn, name_ar, category, category_bn, category_ar, sub, price, unit, tag, photo_key, icon, halal, sort) values (` +
    [lit(p.name), lit(p.name_bn), lit(p.name_ar), lit(p.category), lit(p.category_bn), lit(p.category_ar), lit(p.sub), num(p.price), lit(unitOf(p.name)), lit(p.tag), lit(p.photo_key), lit(p.icon), bool(p.category === 'Meat'), p.sort].join(', ') +
    ') on conflict (name) do nothing;');
}
L.push('', '-- ---- deals (one row per product; skipped if the product already has a deal)');
for (const d of data.deals) {
  L.push(`insert into deals (product_id, pct, active, starts_at, ends_at, sort) select id, ${d.pct}, ${bool(d.active)}, ${d.from ? lit(d.from) + '::timestamptz' : 'null'}, ${d.until ? lit(d.until) + '::timestamptz' : 'null'}, ${d.sort} from products where name = ${lit(d.name)} and not exists (select 1 from deals x where x.product_id = products.id);`);
}
L.push('', '-- ---- website text (key = data-i18n key in index.html; keys starting "ph:" are input placeholders)');
for (const k of Object.keys(content).sort()) {
  const c = content[k];
  L.push(`insert into site_content (key, en, bn, ar) values (${lit(k)}, ${lit(c.en)}, ${lit(c.bn)}, ${lit(c.ar)}) on conflict (key) do nothing;`);
}
L.push('', '-- ---- settings');
const settings = { deals_page_size: data.cfg.pageSize || 4, delivery_fee: 9.99, free_delivery_lb: 100, first_order_free: true };
for (const [k, v] of Object.entries(settings)) L.push(`insert into settings (key, value) values (${lit(k)}, ${lit(JSON.stringify(v))}::jsonb) on conflict (key) do nothing;`);
L.push('');
const out = path.resolve(here, '../supabase/seed.sql');
writeFileSync(out, L.join('\n'));
console.log('wrote', out, '| products', data.products.length, '| deals', data.deals.length, '| text keys', Object.keys(content).length);
