#!/usr/bin/env python3
"""
Builds js/quran-meta.js (small, loaded eagerly) and js/quran-data.js (full text, lazy-loaded)
from the verified source files in tools/source/. Run:  python3 tools/build_quran_data.py

Sources
  Arabic (Hafs, Uthmani) : Tanzil Project  - tools/source/tanzil-uthmani.txt (verbatim, terms of use inside)
  English                : Saheeh International (Tanzil en.sahih, via the `quran-json` npm package)
  Bangla                 : Muhiuddin Khan      (Tanzil bn.bengali, via the `quran-json` npm package)
  Surah names / mushaf   : `quran-meta` npm package + `quran-json` transliteration
The build FAILS if any count is off (must be 114 surahs / 6,236 verses) or text is missing.
"""
import json, re, sys, hashlib, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'source')
def die(msg): print('FAIL:', msg); sys.exit(1)

# ---- Arabic (Tanzil) -------------------------------------------------------
ar = {}
for line in open(os.path.join(SRC, 'tanzil-uthmani.txt'), encoding='utf-8'):
    m = re.match(r'^(\d+)\|(\d+)\|(.+)$', line.rstrip('\n'))
    if m: ar[(int(m[1]), int(m[2]))] = m[3]

en = json.load(open(os.path.join(SRC, 'quran_en.json'), encoding='utf-8'))
bn = json.load(open(os.path.join(SRC, 'quran_bn.json'), encoding='utf-8'))
meta = json.load(open(os.path.join(SRC, 'quran_meta.json'), encoding='utf-8'))

# ---- Validation ------------------------------------------------------------
if len({s for s, _ in ar}) != 114: die('Tanzil: surah count != 114')
if len(ar) != 6236: die('Tanzil: verse count %d != 6236' % len(ar))
if len(en) != 114 or len(bn) != 114: die('translation surah count != 114')
total = {'ar': 0, 'en': 0, 'bn': 0}
AR, EN, BN = [], [], []
for i in range(114):
    n = i + 1
    exp = meta['surahs'][i]['verses']
    if en[i]['id'] != n or bn[i]['id'] != n: die('surah order mismatch at %d' % n)
    if len(en[i]['verses']) != exp or len(bn[i]['verses']) != exp: die('translation verse count mismatch in surah %d' % n)
    a_row, e_row, b_row = [], [], []
    for a in range(1, exp + 1):
        if (n, a) not in ar: die('missing Arabic %d:%d' % (n, a))
        t_ar, t_en, t_bn = ar[(n, a)], en[i]['verses'][a-1]['translation'].strip(), bn[i]['verses'][a-1]['translation'].strip()
        if not (t_ar and t_en and t_bn): die('empty text at %d:%d' % (n, a))
        a_row.append(t_ar); e_row.append(t_en); b_row.append(t_bn)
    total['ar'] += len(a_row); total['en'] += len(e_row); total['bn'] += len(b_row)
    AR.append(a_row); EN.append(e_row); BN.append(b_row)
if set(total.values()) != {6236}: die('verse totals: %r' % total)

# Tanzil prefixes the bismillah to verse 1 of every surah except 1 (where it IS verse 1) and 9 (none).
# The text is kept verbatim in the data; the reader strips the first 4 words at display time.
BIS = ar[(1, 1)]
for n in range(2, 115):
    if n == 9: continue
    if len(AR[n-1][0].split(' ')) < 5: die('verse 1 of surah %d too short to hold bismillah' % n)

# ---- Meta file -------------------------------------------------------------
MEANING_FIX = {5: 'The Table Spread'}  # match the reference design
TRANSLIT_FIX = {3: 'Aal-e-Imran', 4: "An-Nisa'", 36: 'Ya Sin'}  # spellings used in the reference design
surahs = []
for i in range(114):
    n = i + 1; m = meta['surahs'][i]
    surahs.append({'n': n, 'tr': TRANSLIT_FIX.get(n, en[i]['transliteration']), 'en': MEANING_FIX.get(n, m['en']),
                   'bn': bn[i]['translation'], 'ar': en[i]['name'],
                   'v': m['verses'], 'm': 1 if m['meccan'] else 0})
out_meta = {'surahs': surahs, 'pages': meta['pages'], 'juz': meta['juz'], 'hizb': meta['hizb'], 'bismillah': BIS,
            'totals': {'surahs': 114, 'verses': 6236, 'pages': len(meta['pages']), 'juz': len(meta['juz']), 'hizb': len(meta['hizb'])}}
dump = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))
with open(os.path.join(ROOT, 'js', 'quran-meta.js'), 'w', encoding='utf-8') as f:
    f.write('/* Deshi Drop - Quran metadata. Generated by tools/build_quran_data.py - do not edit by hand. */\nwindow.QURAN_META=' + dump(out_meta) + ';\n')

header = ('/* Deshi Drop - full Quran text (114 surahs, 6,236 verses). Generated by tools/build_quran_data.py - do not edit.\n'
          '   Arabic: Tanzil Project (tanzil.net), Uthmani/Hafs, verbatim. English: Saheeh International. Bangla: Muhiuddin Khan. */\n')
with open(os.path.join(ROOT, 'js', 'quran-data.js'), 'w', encoding='utf-8') as f:
    f.write(header + 'window.QURAN_DATA={ar:' + dump(AR) + ',\nen:' + dump(EN) + ',\nbn:' + dump(BN) + '};\n')

print('OK  surahs=114 verses=6236 (ar/en/bn all aligned)')
for k in ('quran-meta.js', 'quran-data.js'):
    p = os.path.join(ROOT, 'js', k); print('   %-16s %8.1f KB' % (k, os.path.getsize(p) / 1024))
